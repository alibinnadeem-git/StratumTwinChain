import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

/** Browser-local integration against actual deployed STRATUM. No tenant session, no
 * production project mutations, no backend writes, no approved-geometry claims. */
test('real NVIDIA SimReady layer archive imports, selects and survives reload in candidate viewer',async({page},testInfo)=>{
 test.setTimeout(150_000);
 const root=path.resolve('.simready-qa-fixtures/nvidia-simready');
 const manifestPath=path.join(root,'manifest.json');
 if(!fs.existsSync(manifestPath))throw new Error('Required pinned NVIDIA real-asset fixture is missing. The dedicated SimReady package download did not complete.');
 const manifest=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
 const audit=JSON.parse(fs.readFileSync(path.join(root,'openusd-stage-audit.json'),'utf8'));
 expect(audit.auditEngine).toContain('Pixar OpenUSD');
 expect(audit.provenance.revision).toBe(manifest.revision);
 expect(audit.provenance.originalRootSha256).toBe(manifest.root_original_sha256);
 expect(audit.stage.authoredMetersPerUnit).toBe(true);
 expect(audit.stage.metersPerUnit).toBe(1);
 expect(audit.stage.authoredUpAxis).toBe(true);
 expect(audit.stage.upAxis).toBe('Z');
 expect(audit.stage.primTypes.Mesh).toBeGreaterThan(0);
 expect(audit.materials.previewSurfaceContexts).toBeGreaterThan(0);
 expect(audit.materials.mdlContexts).toBeGreaterThan(0);
 expect(audit.materials.authoredTexturePaths.length).toBeGreaterThan(0);

 const source=path.resolve(manifest.test_archive);
 expect(manifest.source).toBe('https://huggingface.co/datasets/nvidia/simready-assets');
 expect(manifest.license).toBe('CC BY 4.0');
 expect(manifest.revision).toMatch(/^[a-f0-9]{40}$/);
 expect(manifest.payload_files).toBeGreaterThan(0);
 expect(manifest.texture_files).toBeGreaterThan(0);
 expect(manifest.test_archive_bytes).toBeGreaterThan(10000);
 const errors:string[]=[];
 page.on('pageerror',e=>errors.push(e.message.slice(0,500)));
 page.on('console',msg=>{if(msg.type()==='error'&&/USD|Spatial|3D|model/i.test(msg.text()))errors.push(msg.text().slice(0,500));});
 await page.goto('/compiler');
 await expect(page.locator('input[type="file"][accept*=".usdz"]')).toHaveCount(1);
 await page.locator('input[type="file"][accept*=".usdz"]').setInputFiles(source);
 await expect(page.locator('body')).toContainText('Source compilation updated:',{timeout:65_000});
 const before=await page.evaluate(()=>{
  const graph=JSON.parse(localStorage.getItem('stratum_compiled_graph')||'{}');
  const item=(graph.entities||[]).find((e:any)=>e.kind==='imported-3d-model');
  return {sources:graph.sources?.map((s:any)=>({name:s.name,ext:s.ext,state:s.state})),item:item?{id:item.id,name:item.name,meta:item.meta}:null};
 });
 expect(before.item).not.toBeNull();
 expect(before.item?.meta.sourceType).toBe('USDZ');
 expect(before.item?.meta.sourceSha256).toMatch(/^[0-9a-f]{64}$/);
 expect(before.item?.meta.physicalTruth).toBe(false);
 expect(before.item?.meta.reviewRequired).toBe(true);
 expect(before.item?.meta.usdCompositionStatus).toBe('PARTIAL_GEOMETRY_ONLY');
 expect(before.item?.meta.usdUnresolvedFeatures).toContain('MATERIAL_BINDINGS');
 expect(before.item?.meta.modelBoundsUnitAuthority).toBe('UNVERIFIED_USD_SCENE_UNITS');
 await page.goto('/spatial');
 const canvas=page.locator('canvas[aria-label="Interactive Spatial model"]');
 await expect(canvas).toBeVisible({timeout:30_000});
 await expect.poll(async()=>Number(await canvas.getAttribute('data-clickable-assets')||0),{timeout:45_000}).toBeGreaterThan(0);
 await expect(page.getByLabel('Imported object')).toContainText('nvidia tool hammer');
 await expect(page.getByText('3D IMPORT NEEDS ATTENTION')).toHaveCount(0);
 const beforeReload=await canvas.evaluate((el:HTMLCanvasElement)=>({...el.dataset}));
 await expect.poll(async()=>Number(await canvas.getAttribute('data-native-usd-meshes')||0),{timeout:35_000}).toBeGreaterThan(0);
 const primary=await canvas.evaluate((element:HTMLCanvasElement)=>({...element.dataset}));
 expect(primary.primaryAsset).toBe(before.item!.id);
 const x=Number(primary.primaryHitX),y=Number(primary.primaryHitY);
 const box=await canvas.boundingBox();
 expect(box).not.toBeNull();
 expect(x).toBeGreaterThanOrEqual(0);expect(y).toBeGreaterThanOrEqual(0);
 expect(x).toBeLessThan(box!.width);expect(y).toBeLessThan(box!.height);
 await canvas.click({position:{x,y},force:true});
 await expect(page.getByLabel('Imported object')).toHaveValue(before.item!.id,{timeout:12_000});
 await expect(page.getByText('PARTIAL OPENUSD · GEOMETRY ONLY')).toBeVisible();
 const screenshot=path.join(testInfo.outputDir,'real-nvidia-simready-production.png');
 await page.screenshot({path:screenshot,fullPage:false});
 await page.reload();
 await expect(canvas).toBeVisible({timeout:25_000});
 await expect.poll(async()=>Number(await canvas.getAttribute('data-native-usd-meshes')||0),{timeout:40_000}).toBeGreaterThan(0);
 const after=await page.evaluate(()=>{
  const graph=JSON.parse(localStorage.getItem('stratum_compiled_graph')||'{}');
  return (graph.entities||[]).find((e:any)=>e.kind==='imported-3d-model')?.meta?.sourceSha256||null;
 });
 expect(after).toBe(before.item!.meta.sourceSha256);
 const result={referenceStage:{authoredMetersPerUnit:audit.stage.metersPerUnit,upAxis:audit.stage.upAxis,meshCount:audit.stage.primTypes.Mesh,previewSurfaceMaterials:audit.materials.previewSurfaceContexts,mdlMaterials:audit.materials.mdlContexts,sourceTexturePaths:audit.materials.authoredTexturePaths.length,renderedTextureSlots:Number((await canvas.getAttribute('data-native-usd-textures'))||'0')},origin:process.env.STRATUM_UAT_BASE_URL,license:manifest.license,source:manifest.source,revision:manifest.revision,asset:manifest.asset,sourceFiles:manifest.files,payloadFiles:manifest.payload_files,textureFiles:manifest.texture_files,uncontainedReferences:manifest.uncontained_references,sourceSha256:after,canvasBeforeReload:beforeReload,canvasAfterReload:await canvas.evaluate((el:HTMLCanvasElement)=>({...el.dataset})),browserErrors:errors};
 console.log('NVIDIA_SIMREADY_PRODUCTION_RESULT',JSON.stringify(result));
 expect(errors.filter(s=>/usd|3d|spatial/i.test(s))).toEqual([]);
});
