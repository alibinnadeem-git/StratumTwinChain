import assert from 'node:assert/strict';
import {readFile,writeFile,unlink} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import ts from 'typescript';
const url=new URL(`../lib/.qa-alignment-${randomUUID()}.mjs`,import.meta.url);
try{
 await writeFile(url,ts.transpileModule(await readFile(new URL('../lib/sheet-alignment.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText);
 const {solveSheetTransform,applySheetTransform,restoreSheetCoordinates,solveSheetXYTransform,applySheetXYTransform,restoreSheetXYCoordinates,sheetXYValidationResidual}=await import(url.href);
 const source=[{x:2,y:3},{x:6,y:3}],target=[{x:100,y:200},{x:100,y:208}];
 const t=solveSheetTransform(source,target,'L2',4.25);
 const e={id:'a',source:'plan',kind:'line',name:'wall',x:2,y:3,z:0,x2:6,y2:3,z2:0,vertices:source,meta:{sourceSha256:'abc',page:2,coordinateUnits:'sheet',elevationKnown:false,physicalElevationKnown:false,physicalTruth:false,reviewRequired:true}};
 const snapshot=JSON.stringify(e),aligned=applySheetTransform(e,t);
 assert.equal(JSON.stringify(e),snapshot,'source entity is immutable');
 assert.deepEqual([aligned.x,aligned.y,aligned.x2,aligned.y2],[100,200,100,208]);
 assert.equal(aligned.z,4.25);assert.equal(aligned.floor,'L2');assert.equal(aligned.meta.sourceSha256,'abc');assert.equal(aligned.meta.alignmentVerified,false);
 assert.equal(aligned.meta.elevationKnown,false,'reviewed sheet elevation must not become physical/known elevation');
 assert.equal(aligned.meta.physicalElevationKnown,false,'reviewed sheet elevation must remain physically unverified');
 assert.equal(aligned.meta.physicalTruth,false);
 assert.equal(aligned.meta.reviewRequired,true);
 assert.equal(aligned.meta.zCandidateMeters,4.25);
 assert.equal(aligned.meta.zCandidateReferencePoint,'PROJECT_DATUM');
 assert.equal(aligned.meta.zResolutionStatus,'RESOLVED_DESIGN_CANDIDATE');
 assert.equal(aligned.meta.zResolutionAuthority,'HUMAN_REVIEWED_SHEET_ELEVATION');
 assert.equal(aligned.meta.zResolutionCoordinateFrame,'PROJECT_REVIEW_DATUM');
 assert.equal(aligned.meta.zPlacementAuthority,'HUMAN_REVIEWED_SHEET_ELEVATION');
 assert.equal(aligned.meta.sheetElevationReviewRequired,true);
 assert.deepEqual(applySheetTransform(aligned,t),aligned,'reapply does not compound transforms');
 const reset=solveSheetTransform(source,source,'L1',0),restored=applySheetTransform(aligned,reset);
 const restoredOriginal=restoreSheetCoordinates(aligned);
 assert.equal(restoredOriginal.meta.sheetTransform,undefined);assert.deepEqual(restoredOriginal.vertices,e.vertices);assert.deepEqual(restored.vertices,e.vertices);assert.equal(restored.x,e.x);assert.equal(restored.y,e.y);
 assert.equal(restoredOriginal.meta.coordinateUnits,'sheet');
 assert.equal(restoredOriginal.meta.elevationKnown,false);
 assert.equal(restoredOriginal.meta.physicalElevationKnown,false);
 assert.equal(restoredOriginal.meta.zCandidateMeters,undefined,'restore must remove review-only Z candidate when it did not exist before');
 assert.equal(restoredOriginal.meta.zResolutionStatus,undefined);
 assert.equal(restoredOriginal.meta.zPlacementAuthority,undefined);
 assert.equal(restoredOriginal.meta.sheetElevationReviewRequired,undefined);
 assert.throws(()=>solveSheetTransform([source[0],source[0]],target,'L1',0));
 assert.throws(()=>solveSheetTransform(source,target,'UNRESOLVED',0));
 assert.throws(()=>solveSheetTransform(source,target,'L1',NaN));
 const xy=solveSheetXYTransform(source,target),xyResidual=sheetXYValidationResidual({x:4,y:3},{x:100,y:204},xy);
 assert.ok(xyResidual<1e-9,'third control point validates independent XY transform');
 const unknownZ={id:'xy',source:'sheet.pdf',kind:'sheet-callout-candidate',name:'review',x:2,y:3,meta:{elevationKnown:false,physicalElevationKnown:false,coordinateUnits:'sheet'}};
 const xyApplied=applySheetXYTransform(unknownZ,xy,{residualMeters:xyResidual,toleranceMeters:.25});
 assert.equal(xyApplied.z,undefined,'XY calibration must not invent Z');
 assert.equal(xyApplied.meta.elevationKnown,false,'XY calibration must preserve elevation uncertainty');
 assert.equal(xyApplied.meta.physicalElevationKnown,false,'XY calibration must preserve physical elevation uncertainty');
 assert.equal(xyApplied.meta.planXYAuthority,'HUMAN_VALIDATED_3_POINT_TRANSFORM');
 assert.equal(xyApplied.meta.physicalPositionVerified,false,'validated plan transform is not as-built proof');
 const xyRestored=restoreSheetXYCoordinates(xyApplied);
 assert.deepEqual([xyRestored.x,xyRestored.y],[2,3]);assert.equal(xyRestored.z,undefined);
 const viewer=await readFile(new URL('../components/CompiledGraphViewer.tsx',import.meta.url),'utf8');
 const sheetReview=await readFile(new URL('../components/SheetReview.tsx',import.meta.url),'utf8');
 assert.match(viewer,/return e\.meta\?\.elevationKnown===true\|\|e\.meta\?\.physicalElevationKnown===true/,'viewer only treats explicit known-elevation flags as physical/known Z');
 assert.match(sheetReview,/Reviewed elevation \/ datum \(m\)/);
 assert.doesNotMatch(sheetReview,/Measured elevation \(m\)/,'review UI must not imply field measurement provenance');
 assert.match(sheetReview,/reviewed design datum only unless separately backed by field\/measurement evidence/);
 console.log('PASS: control point alignment, XY-only calibration, independent validation, reviewed-Z truth separation, source immutability, restoration and invalid input guards');
}finally{await unlink(url)}
